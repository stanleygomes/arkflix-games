import { axe, expect, gameOption, open, settings, test } from './fixtures'

test('ocultar jogo: some do Início e da busca, volta pela Biblioteca', async ({ page, app }) => {
  await open(page, app)
  await page.locator('.shelf [data-game][aria-label^="Mega Man X"]').first().click()
  await page.getByRole('button', { name: 'Opções', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'Opções' })
  await expect(menu.getByRole('button', { name: /^Listas/ })).toBeFocused()
  await axe(page, 'opções do jogo')
  await menu.getByRole('button', { name: 'Ocultar da biblioteca' }).click()
  await expect(menu).toBeHidden()
  await expect(page.locator('.facts')).toContainText('Oculto')
  expect(Object.values(JSON.parse(app.read(`${app.data}/state.json`)).hidden)).toEqual([true])

  await page.keyboard.press('Escape')
  await expect(page.locator('.shelf [data-game][aria-label^="Super Mario World"]').first()).toBeVisible()
  await expect(page.locator('.shelf [data-game][aria-label^="Mega Man X"]')).toHaveCount(0)
  await page.keyboard.press('/')
  await page.keyboard.type('mega man')
  await expect(page.locator('#results-count')).toBeVisible()
  await expect(page.locator('.results [data-game]')).toHaveCount(0)
  await page.keyboard.press('Escape')

  await settings(page)
  await page.getByRole('button', { name: 'Jogos ocultos (1)' }).click()
  await expect(page.getByRole('heading', { name: 'Jogos ocultos' })).toBeVisible()
  await page.locator('.grid [data-game]').filter({ hasText: 'Mega Man X' }).click()
  await gameOption(page, 'Mostrar na biblioteca')
  await expect(page.locator('.facts')).not.toContainText('Oculto')
  await page.keyboard.press('Escape')
  await expect(page.locator('.grid [data-game]')).toHaveCount(0)
})

test('apagar do PC: mostra quanto libera, mantém os saves e recusa pasta só de leitura', async ({ page, app }) => {
  await open(page, app)
  await page.keyboard.press('/')
  await page.keyboard.type('crash')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(page.locator('h1')).toHaveText('Crash Bandicoot')
  await gameOption(page, 'Apagar do PC')
  const ask = page.getByRole('alertdialog')
  await expect(ask).toContainText('Libera 43 B')
  await expect(ask).toContainText('saves e pontos salvos não são apagados')
  await axe(page, 'confirmar apagar jogo')
  await ask.getByRole('button', { name: 'Cancelar' }).click()
  expect(app.exists('home/Games/roms/psx/Crash Bandicoot (USA)/Crash Bandicoot (USA).bin')).toBe(true)

  // cancelar volta pro menu
  await page.getByRole('dialog', { name: 'Opções' }).getByRole('button', { name: 'Apagar do PC' }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Apagar do PC' }).click()
  await expect(page.locator('h1')).not.toHaveText('Crash Bandicoot')
  expect(app.exists('home/Games/roms/psx/Crash Bandicoot (USA)')).toBe(false)
  expect(app.exists('home/Games/roms/psx')).toBe(true)

  // pasta só de leitura (Jogos antigos): nem aparece
  await page.keyboard.press('/')
  await page.keyboard.type('mario bros')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(page.locator('h1')).toHaveText(/Super Mario Bros/)
  await page.getByRole('button', { name: 'Opções', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Opções' }).getByRole('button', { name: 'Apagar do PC' })).toHaveCount(0)
})

test('configurar este jogo: core, imagem e proporção só pra ele', async ({ page, app }) => {
  await open(page, app)
  await page.locator('.shelf [data-game][aria-label^="Super Mario World"]').first().click()
  await gameOption(page, 'Configurar este jogo')
  const dlg = page.getByRole('dialog', { name: 'Configurar este jogo' })
  const core = dlg.getByRole('radiogroup', { name: 'Core' })
  await expect(core.getByRole('radio')).toHaveText(['Padrão (Snes9x)', 'bsnes'])
  await expect(core.getByRole('radio', { name: /Padrão/ })).toBeFocused()
  await expect(dlg.getByRole('radiogroup', { name: 'Imagem' }).getByRole('radio')).toHaveText(['Padrão', 'Pixels nítidos', 'Suave', 'CRT (TV de tubo)'])
  await axe(page, 'configurar este jogo')

  // pelo controle: direita escolhe o bsnes
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Enter')
  await expect(core.getByRole('radio', { name: 'bsnes' })).toHaveAttribute('aria-checked', 'true')
  await dlg.getByRole('radio', { name: 'Pixels nítidos' }).click()
  await dlg.getByRole('radio', { name: '4:3' }).click()
  await expect(dlg.getByRole('radio', { name: '4:3' })).toHaveAttribute('aria-checked', 'true')
  expect(Object.values(JSON.parse(app.read(`${app.data}/gameconfig.json`)))).toEqual([{ core: 'bsnes', image: 'sharp', aspect: '4:3' }])
  await dlg.getByRole('button', { name: 'Pronto' }).click()
  await expect(dlg).toBeHidden()
  await expect(page.getByRole('button', { name: 'Opções', exact: true })).toBeFocused()

  await page.getByRole('button', { name: 'Jogar do início' }).click()
  await expect(page.getByRole('dialog', { name: /Jogando/ })).toBeHidden({ timeout: 8000 })
  expect(app.calls()).toMatch(/retroarch\|.*retroarch-game\.cfg.*-L .*bsnes_libretro\.so/)
  expect(app.read(`${app.data}/retroarch-game.cfg`)).toContain('video_scale_integer = "true"')
})
